const POEMS = POEM_SRC.trim().split('\n').map((line, i) => {
  const [author, kami, shimo, kamiKana, shimoKana, kamiYomi, shimoYomi] = line.split('|');
  return { no: i + 1, author, kami, shimo, kamiKana, shimoKana, kamiYomi, shimoYomi };
});

// 決まり字：上の句の頭から何文字聞けば、その札だと確定するか
// pool に含まれる歌の中で一意になる最短の頭の部分を返す
// （「を」と「お」、「ゐ」と「い」、「ゑ」と「え」は同じ音として比べる）
const soundOf = s => s.replace(/ /g, '').replace(/を/g, 'お').replace(/ゐ/g, 'い').replace(/ゑ/g, 'え');
function kimarijiOf(poem, pool) {
  const me = soundOf(poem.kamiKana);
  let len = 1;
  for (const p of pool) {
    if (p.no === poem.no) continue;
    const other = soundOf(p.kamiKana);
    let k = 0;
    while (k < me.length && me[k] === other[k]) k++;
    len = Math.max(len, k + 1);
  }
  return poem.kamiKana.replace(/ /g, '').slice(0, len);
}

POEMS.forEach(p => { p.kimariji = kimarijiOf(p, POEMS); });

if (typeof module !== 'undefined') module.exports = { POEMS, kimarijiOf };
